import { kit, u, COLOR } from './kit.js';
import { amountInWords, inrNumber } from './words.js';
import { letterhead, signatureBlock, stampAt, niceDate } from './common.js';
import { sampleMark } from './look.js';

/** The payment voucher for money the school paid out (a vendor, a bill), A5. It has the same look as the fee receipt. */
export function drawVoucher(doc, look, d, { sample = false } = {}) {
  const k = kit(doc, look.color);
  const W = doc.page.width; const H = doc.page.height; const L = u(32); const R = W - u(32); const CW = R - L;
  const accent = look.color;
  let y = u(32);
  y = letterhead(k, doc, look, { y, left: L, right: R, logoPx: 56, namePx: 19, title: 'PAYMENT VOUCHER', big: d.voucherNo || '—', small: niceDate(d.paidOn), extraLine: '' }) + u(14);

  const cells = [
    [['Paid to', d.vendor || d.paidTo || '—'], ['Vendor code · Category', [d.vendorCode, d.vendorCategory].filter(Boolean).join(' · ') || '—']],
    [['Department · Work or item', [d.department, d.work].filter(Boolean).join(' · ') || '—'], ['Bill or voucher no. · Bill date', [d.billNo, d.billDate ? niceDate(d.billDate) : ''].filter(Boolean).join(' · ') || '—']],
  ];
  const cellH = u(36); const boxH = u(20) + cellH * 2;
  k.box(L, y, CW, boxH); k.vline(L + CW / 2, y, y + boxH);
  cells.forEach((col, ci) => col.forEach(([lab, val], i) => {
    const x0 = L + (ci ? CW / 2 : 0) + u(14); const ty = y + u(10) + i * (cellH + u(6));
    k.text(lab, x0, ty, { s: u(12), c: COLOR.muted }); k.text(k.fit(val || '—', 'Semi', u(13), CW / 2 - u(28)), x0, ty + u(12) * 1.4, { f: 'Semi', s: u(13) });
  }));
  y += boxH + u(14);

  const headH = u(30); const lineH = u(34); const totalH = u(46); const amtW = u(100);
  const tableH = headH + lineH + totalH;
  k.box(L, y, CW, tableH);
  doc.save().roundedRect(L, y, CW, headH, 4.5).clip().rect(L, y, CW, headH).fill(COLOR.head).restore();
  k.hline(L, R, y + headH);
  const hy = y + (headH - u(12)) / 2;
  k.text('PARTICULARS', L + u(14), hy, { f: 'Bold', s: u(12), c: accent, spacing: 0.7 });
  k.text('AMOUNT (₹)', R - u(14) - amtW, hy, { f: 'Bold', s: u(12), c: accent, spacing: 0.7, w: amtW, align: 'right' });
  const ry = y + headH; const ty1 = ry + (lineH - u(13)) / 2;
  k.text(k.fit(d.title, 'Sans', u(13), CW - u(28) - amtW - u(20)), L + u(14), ty1, { s: u(13) });
  k.text(inrNumber(d.amount), R - u(14) - amtW, ty1, { s: u(13), w: amtW, align: 'right' });
  k.hline(L, R, ry + lineH, { c: COLOR.row });
  const ty = y + tableH - totalH;
  k.hline(L, R, ty, { c: accent, lw: 1.5 });
  k.text('Total paid', L + u(14), ty + (totalH - u(13)) / 2, { f: 'Bold', s: u(13) });
  k.text(`₹ ${inrNumber(d.amount)}`, L + u(14), ty + (totalH - u(20)) / 2, { f: 'Serif', s: u(20), c: accent, w: CW - u(28), align: 'right' });
  y += tableH + u(14);

  k.para(amountInWords(d.amount), L, y, CW, { s: u(13) }); y += u(13) * 1.4 + u(3);
  k.text(k.fit(d.payLine, 'Sans', u(12), CW), L, y, { s: u(12), c: COLOR.soft }); y += u(12) * 1.4 + u(3);
  if (d.note) { k.text(k.fit(`Note: ${d.note}`, 'Sans', u(12), CW), L, y, { s: u(12), c: COLOR.soft }); y += u(12) * 1.4 + u(3); }
  y += u(8);

  const bh = u(54); k.box(L, y, CW, bh); k.vline(L + CW / 2, y, y + bh);
  k.text(`Bill amount ₹ ${inrNumber(d.billAmount)}`, L + u(14), y + u(8), { s: u(12), c: COLOR.muted }); k.text(`Paid so far ₹ ${inrNumber(d.paidSoFar)}`, L + u(14), y + u(8) + u(12) * 1.4, { f: 'Semi', s: u(13) });
  const nx = L + CW / 2 + u(14);
  k.text('Balance on this bill', nx, y + u(8), { s: u(12), c: COLOR.muted }); k.text(d.balance > 0.001 ? `₹ ${inrNumber(d.balance)}` : 'Paid in full', nx, y + u(8) + u(12) * 1.4, { f: 'Semi', s: u(13) });

  const footerTop = H - u(26) - u(12) - u(10);
  const sigH = u(52); const sigBlock = sigH + u(4) + u(36);
  const sy = footerTop - u(14) - sigBlock;
  signatureBlock(k, doc, { x: L, y: sy, w: u(200), h: sigH, img: look.receipt.signature, caption: look.receipt.caption, sample, color: look.color });
  stampAt(k, doc, { cx: R - u(60), cy: sy + sigBlock / 2, size: u(104), img: look.receipt.stamp, sample, name: look.name });
  k.hline(L, R, footerTop);
  const fy = footerTop + u(8);
  k.text(`Recorded by ${d.byName || '—'}. This is a computer-generated voucher.`, L, fy, { s: u(12), c: COLOR.muted });
  k.text('Generated by AtKaksha', L, fy, { s: u(12), c: COLOR.muted, w: CW, align: 'right' });
  if (sample) sampleMark(doc);
}
